def status_of(sk, spk, cat, n, jobs):
    out_dir = os.path.join(T.OUT, spk["faction"], sk)
    f = os.path.join(out_dir, T.file_name(cat, n) + ".ogg")
    if os.path.exists(f):
        return "shipped"
    tried = [j for j in jobs if j["speaker"] == sk and (cat, n) in T.job_items(j)]
    if tried:
        return "rejected (regenerate)"
    return "not generated"


def write_doc(script, jobs):
    L = [HEADER, GEN]
    L.append("## Casting\n")
    L.append("| Speaker | Faction | Def ids | Voice id | Preset | Tic | Post-chain (ffmpeg) |")
    L.append("|---|---|---|---|---|---|---|")
    for sk, spk in script["speakers"].items():
        vid = spk["voice_id"] + (f" + {spk['voice_id_2']}" if spk.get("voice_id_2") else "")
        L.append(f"| {spk['name']} (`{sk}`) | {spk['faction']} | {', '.join('`' + d + '`' for d in spk['def_ids']) or '— (advisor)'} | "
                 f"`{vid}` | {spk['voice_name']}; {spk['casting']} | {spk['tic']} | `{spk['post']}` |")
    L.append("")
    totals = {"shipped": 0, "not generated": 0, "rejected (regenerate)": 0}
    for sk, spk in script["speakers"].items():
        L.append(f"## {spk['name']} (`{sk}`, {spk['faction']})\n")
        L.append(f"Source: {spk['source']}. Tags: " + ", ".join(f"{k} `{v}`" for k, v in spk["tags"].items()) + ".")
        if spk.get("notes"):
            L.append("Notes: " + "; ".join(f"{k}: {v}" for k, v in spk["notes"].items()) + ".")
        L.append("")
        L.append("| Speaker | Category | # | Text | Words | Voice id | File | Status |")
        L.append("|---|---|---|---|---|---|---|---|")
        for cat in T.CAT_ORDER:
            if cat not in spk["lines"]:
                continue
            for n, text in enumerate(spk["lines"][cat], 1):
                st = status_of(sk, spk, cat, n, jobs)
                totals[st] = totals.get(st, 0) + 1
                path = f"assets/audio/voice/{spk['faction']}/{sk}/{T.file_name(cat, n)}.ogg"
                L.append(f"| {sk} | `{cat}` | {n} | {text} | {T.words(text)} | `{spk['voice_id']}` | `{path}` | {st} |")
        L.append("")
    n_all = sum(totals.values())
    L.insert(2, f"**Totals:** {n_all} lines written; {totals.get('shipped', 0)} shipped, "
                f"{totals.get('rejected (regenerate)', 0)} rejected and waiting for a retake, {totals.get('not generated', 0)} not generated.\n")
    with open(T.DOC, "w", encoding="utf-8") as f:
        f.write("\n".join(L).rstrip() + "\n")
